// Writes `@effectified/pi-ai/providers/<name>`, one module per pi-ai provider, so an application registers a
// provider without importing pi-ai: each re-exports the provider's constructor, a pure function whose value
// `Models.layer` takes. With `check`, fails when the modules differ from what pi-ai has (a provider Pi added or
// removed), naming each.
// Usage: node effect/scripts/providers.ts [check]

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./packages.ts";

const upstream = join(ROOT, "packages/ai/src/providers");
const target = join(ROOT, "packages/ai-effect/src/providers");

// `faux` is a provider for tests: `@effectified/pi-ai/testing` exports it with its helpers.
const TESTING = new Set(["faux"]);

const CONSTRUCTOR = /^export function (\w+Provider)\(/gm;

const wanted = new Map<string, string>();
for (const file of readdirSync(upstream).sort()) {
	if (!file.endsWith(".ts") || file.endsWith(".models.ts") || file.endsWith(".d.ts")) continue;
	const name = file.slice(0, -".ts".length);
	if (TESTING.has(name)) continue;
	const constructors = [...readFileSync(join(upstream, file), "utf8").matchAll(CONSTRUCTOR)].map((match) => match[1]);
	if (constructors.length === 0) continue;
	wanted.set(`${name}.ts`, moduleSource(name, constructors));
}

const present = existsSync(target) ? readdirSync(target).filter((file) => file.endsWith(".ts")) : [];
const stale = present.filter((file) => !wanted.has(file));
const differing = [...wanted].filter(
	([file, source]) => !existsSync(join(target, file)) || readFileSync(join(target, file), "utf8") !== source,
);

if (process.argv[2] === "check") {
	if (stale.length + differing.length > 0) {
		console.error(
			"@effectified/pi-ai/providers differs from pi-ai's providers; run node effect/scripts/providers.ts:",
		);
		for (const file of stale) console.error(`  ${file}: pi-ai has no such provider any more`);
		for (const [file] of differing) console.error(`  ${file}: missing or out of date`);
		process.exit(1);
	}
	console.log(`@effectified/pi-ai/providers has all ${wanted.size} pi-ai providers.`);
} else {
	mkdirSync(target, { recursive: true });
	for (const file of stale) rmSync(join(target, file));
	for (const [file, source] of differing) writeFileSync(join(target, file), source);
	console.log(`Wrote ${differing.length} and removed ${stale.length} of ${wanted.size} provider modules.`);
}

/** A provider module: its constructors, re-exported from pi-ai's module of the same name. */
function moduleSource(name: string, constructors: readonly string[]): string {
	return [
		`// pi-ai's ${name} provider, for \`Models.layer\`. Generated by effect/scripts/providers.ts: do not edit.`,
		"",
		`export { ${constructors.join(", ")} } from "@earendil-works/pi-ai/providers/${name}";`,
		"",
	].join("\n");
}
